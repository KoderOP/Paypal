"""Run every offline evaluation and write evals/results/REPORT.md.

    python -m evals.run_all            # offline: agent (rules), guardrail red-team, forecast backtest
    GROQ_API_KEY=... python -m evals.run_all --llm   # also the live Groq agent benchmark

Each step is its own process so the pinned clock and temporary databases never leak between them.
"""
import argparse
import json
import subprocess
import sys

from evals.common import RESULTS, ROOT


def step(*args: str) -> None:
    print(f"\n$ python -m {' '.join(args)}", flush=True)
    subprocess.run([sys.executable, "-m", *args], cwd=ROOT.parent, check=True)


def pct(v) -> str:
    return "n/a" if v is None else f"{v * 100:.1f}%"


def report() -> str:
    def load(name):
        p = RESULTS / name
        return json.loads(p.read_text()) if p.exists() else None

    lines = ["# FINORA evaluation report", "",
             "Generated by `python -m evals.run_all`. Every number below was produced by the scripts in `backend/evals/`.", ""]
    for mode in ("rules", "llm"):
        a = load(f"agent_{mode}.json")
        if not a:
            if mode == "llm":
                lines += ["## Agent benchmark: Groq (live)", "", "_Not run: needs `GROQ_API_KEY`. Run `python -m evals.agent_eval --mode llm`._", ""]
            continue
        title = "deterministic planner (offline)" if mode == "rules" else f"{a['provider']} · {a['model']} (live)"
        lines += [f"## Agent benchmark: {title}", "", f"Commit `{a['commit']}` · {a['summary']['overall']['n']} cases", "",
                  "| Slice | n | Tool accuracy | Argument accuracy | Grounded | Guardrail rewrites | p50 latency |",
                  "|---|---|---|---|---|---|---|"]
        rows = [("Overall", a["summary"]["overall"]), ("Wording the planner was written for", a["summary"]["seen_wording"]),
                ("Held-out paraphrases", a["summary"]["paraphrases"])] + \
               [(f"· {k}", v) for k, v in a["summary"]["by_category"].items()]
        for name, s in rows:
            lines.append(f"| {name} | {s['n']} | {pct(s['tool_accuracy'])} | {pct(s['arg_accuracy'])} | {pct(s['grounded_rate'])} | "
                         f"{pct(s['guardrail_replaced'])} | {s['latency_ms_p50']} ms |")
        lines.append("")
    g = load("guardrail_redteam.json")
    if g:
        s, f = g["summary"], g["ablation_flat_1pct_tolerance"]
        lines += ["## Guardrail red-team", "", f"{s['faithful_n']} faithful drafts, {s['corrupted_n']} corrupted drafts.", "",
                  "| Variant | Kind | n | Shipped (precision-aware) | Ablation (flat 1%) |", "|---|---|---|---|---|"]
        for v, d in s["by_variant"].items():
            k = "detection_rate" if "detection_rate" in d else "acceptance_rate"
            lines.append(f"| {v} | {'caught' if k == 'detection_rate' else 'accepted'} | {d['n']} | {pct(d[k])} | {pct(f['by_variant'][v][k])} |")
        lines += ["", f"**Faithful drafts accepted:** {pct(s['faithful_acceptance_rate'])} (flat: {pct(f['faithful_acceptance_rate'])}) · "
                  f"**Corruptions caught:** {pct(s['corruption_detection_rate'])} (flat: {pct(f['corruption_detection_rate'])})", ""]
    b = load("forecast_backtest.json")
    if b:
        lines += ["## Forecast backtest (walk-forward, 30-day horizon)", ""]
        for cond, r in b["results"].items():
            lines += [f"### {cond} · {r.get('n_histories', '?')} histories × {r.get('cutoffs_per_history', '?')} cut-offs", "",
                      "| Model | Path MAE | % of monthly income | Low-point MAE | Purchase-decision accuracy | False-safe rate |",
                      "|---|---|---|---|---|---|"]
            for m, a in sorted(r["aggregate"].items(), key=lambda kv: kv[1]["path_mae"]):
                lines.append(f"| {m} | ₹{a['path_mae']:,} | {a['path_mae_pct_income']}% | ₹{a['low_point_mae']:,} | "
                             f"{pct(a['decision_accuracy'])} | {pct(a['false_safe_rate'])} |")
            lines.append("")
        lines += ["Synthetic histories only: see `docs/EVALUATION.md` for caveats, and run "
                  "`python -m evals.forecast_backtest --file <your export.csv>` on real data.", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--llm", action="store_true")
    args = ap.parse_args()
    step("evals.agent_eval", "--mode", "rules")
    if args.llm:
        step("evals.agent_eval", "--mode", "llm")
    step("evals.guardrail_redteam")
    step("evals.forecast_backtest")
    (RESULTS / "REPORT.md").write_text(report())
    print(f"\nWrote {RESULTS / 'REPORT.md'}")


if __name__ == "__main__":
    main()
